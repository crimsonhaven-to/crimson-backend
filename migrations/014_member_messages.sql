-- 014_member_messages.sql
--
-- Messages between members: private two-person chats and named groups, where a
-- message can carry a song or a show next to its text.
--
-- | table               | holds                                                     |
-- | ------------------- | --------------------------------------------------------- |
-- | accounts.handle     | the unique @name other members find you by                |
-- | messaging_rooms     | one conversation, 'direct' (two people) or 'group'        |
-- | messaging_members   | who is in a room, and how far each of them has read       |
-- | messaging_messages  | the messages, oldest first by id                          |
-- | messaging_blocks    | members someone never wants a direct message from         |
--
-- Handles
-- -------
-- username stays a cosmetic, non-unique greeting. The handle is the identity:
-- stored lowercase, so the plain unique constraint is case insensitive. It is
-- NULL until the member picks one, and messaging asks for it first.
--
-- Rooms
-- -----
-- A direct room is found again by direct_key ('<lower id>:<higher id>'), so two
-- people never end up with two chats. Nobody leaves one; blocking is how you stop
-- it. A group is left by deleting your membership, and the last one out deletes
-- the room and its messages.
--
-- Reading
-- -------
-- last_read_id is the newest message id a member has seen, so unread is every
-- later message someone else sent. There is no push: clients poll, which works
-- the same behind any number of API replicas.
--
-- Messages are kept until their room is deleted. A deleted account leaves its
-- messages behind with sender_id NULL, shown as a former member.

ALTER TABLE accounts ADD COLUMN IF NOT EXISTS handle TEXT UNIQUE;

CREATE TABLE IF NOT EXISTS messaging_rooms (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind            TEXT NOT NULL CHECK (kind IN ('direct', 'group')),
    name            TEXT,
    direct_key      TEXT UNIQUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_message_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS messaging_members (
    room_id      BIGINT NOT NULL REFERENCES messaging_rooms(id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES accounts(user_id) ON DELETE CASCADE,
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_read_id BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (room_id, user_id)
);

-- The inbox and the unread badge start from the member.
CREATE INDEX IF NOT EXISTS idx_messaging_members_user ON messaging_members(user_id);

CREATE TABLE IF NOT EXISTS messaging_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT NOT NULL REFERENCES messaging_rooms(id) ON DELETE CASCADE,
    sender_id  BIGINT REFERENCES accounts(user_id) ON DELETE SET NULL,
    body       TEXT NOT NULL DEFAULT '',
    -- A snapshot of the song or show, so the card still reads right after the
    -- song leaves the library.
    attachment JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Every read is one room, paged by id.
CREATE INDEX IF NOT EXISTS idx_messaging_messages_room ON messaging_messages(room_id, id);

CREATE TABLE IF NOT EXISTS messaging_blocks (
    user_id    BIGINT NOT NULL REFERENCES accounts(user_id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES accounts(user_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, blocked_id)
);
